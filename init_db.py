# Выводим сообщение в консоль, чтобы пользователь видел, что происходит
print("🔌 Подключаемся к PostgreSQL...")

# psycopg2.connect() - устанавливает соединение с базой данных
# Параметры подключения:
#   dbname - имя базы данных (мы создали её в прошлом шаге через psql)
#   user - имя пользователя PostgreSQL (по умолчанию postgres)
#   password - пароль, который вы задали при установке
#   host - адрес сервера (localhost = этот же компьютер)
#   port - порт PostgreSQL (5432 = стандартный)
conn = psycopg2.connect(
    dbname="moscow_metro",  # База данных, которую мы создали командой CREATE DATABASE
    user="postgres",         # Главный пользователь PostgreSQL
    password=PASSWORD,       # Ваш пароль (подставляется из переменной выше)
    host="localhost",        # localhost = текущий компьютер
    port="5432"              # Стандартный порт PostgreSQL
)

# cursor() - создаёт курсор (объект для выполнения SQL-запросов)
# Курсор — это как "карандаш", которым мы пишем команды базе данных
cursor = conn.cursor()

# Сообщаем, что подключение успешно
print("✅ Подключено!")

# ============================================================
# ШАГ 2: УДАЛЯЕМ СТАРЫЕ ТАБЛИЦЫ (ЕСЛИ ОНИ ЕСТЬ)
# ============================================================

# Выводим сообщение о начале операции
print("\n🗑️ Удаляем старые таблицы...")

# cursor.execute() - выполняет SQL-команду
# DROP TABLE IF EXISTS - удаляет таблицу, если она существует
# CASCADE - также удаляет всё, что зависит от таблицы (например, связи)
# Порядок важен: сначала удаляем places (зависит от stations),
# потом stations (зависит от lines), потом lines

# Удаляем таблицу places (достопримечательности)
cursor.execute("DROP TABLE IF EXISTS places CASCADE")

# Удаляем таблицу stations (станции метро)
cursor.execute("DROP TABLE IF EXISTS stations CASCADE")

# Удаляем таблицу lines (линии метро)
cursor.execute("DROP TABLE IF EXISTS lines CASCADE")

# Сообщаем, что старые таблицы удалены
print("✅ Старые таблицы удалены")

# ============================================================
# ШАГ 3: СОЗДАЁМ НОВЫЕ ТАБЛИЦЫ
# ============================================================

# Выводим сообщение
print("\n📦 Создаём новые таблицы...")

# --- ТАБЛИЦА lines (линии метро) ---
# CREATE TABLE IF NOT EXISTS - создаёт таблицу, только если её ещё нет
#
# Поля таблицы:
#   id - SERIAL PRIMARY KEY
#        SERIAL = автоматически увеличивающееся целое число (1,2,3...)
#        PRIMARY KEY = главный ключ, уникальный идентификатор каждой записи
#   name - TEXT NOT NULL UNIQUE
#        TEXT = текст без ограничения длины (вместо VARCHAR(100))
#        NOT NULL = поле не может быть пустым
#        UNIQUE = значение должно быть уникальным (нельзя добавить две одинаковые линии)
cursor.execute("""
    CREATE TABLE IF NOT EXISTS lines (
        id SERIAL PRIMARY KEY,
        name TEXT NOT NULL UNIQUE
    )
""")

# --- ТАБЛИЦА stations (станции метро) ---
# Поля таблицы:
#   id - SERIAL PRIMARY KEY (уникальный номер станции)
#   name - TEXT NOT NULL (название станции - теперь без ограничения длины)
#   line_id - INTEGER REFERENCES lines(id)
#        INTEGER = целое число
#        REFERENCES lines(id) = внешний ключ, ссылается на id в таблице lines
#        Это значит: каждая станция принадлежит какой-то линии
#   fact - TEXT (длинный текст с интересным фактом о станции)
cursor.execute("""
    CREATE TABLE IF NOT EXISTS stations (
        id SERIAL PRIMARY KEY,
        name TEXT NOT NULL,
        line_id INTEGER REFERENCES lines(id),
        fact TEXT
    )
""")

# --- ТАБЛИЦА places (достопримечательности) ---
# Поля таблицы:
#   id - SERIAL PRIMARY KEY (уникальный номер места)
#   station_id - INTEGER REFERENCES stations(id) (к какой станции относится)
#   name - TEXT NOT NULL (название места - теперь без ограничения)
#   place_type - TEXT (тип: музей, кафе, парк... - без ограничения)
#   description - TEXT (описание места)
#   walking_minutes - INTEGER DEFAULT 0 (минут пешком от метро, по умолчанию 0)
cursor.execute("""
    CREATE TABLE IF NOT EXISTS places (
        id SERIAL PRIMARY KEY,
        station_id INTEGER REFERENCES stations(id),
        name TEXT NOT NULL,
        place_type TEXT,
        description TEXT,
        walking_minutes INTEGER DEFAULT 0
    )
""")

# Сообщаем, что таблицы созданы
print("✅ Таблицы созданы")

# ============================================================
# ШАГ 4: ФУНКЦИЯ ДЛЯ БЕЗОПАСНОГО ЧТЕНИЯ CSV
# ============================================================

def safe_get(row, key):
    """
    Безопасно получает значение из строки CSV.
    
    Параметры:
        row - словарь с данными строки (одна строка из CSV)
        key - название колонки (например, 'station_name')
    
    Возвращает:
        строку с удалёнными пробелами, или пустую строку "", если значение None
    
    ЗАЧЕМ ЭТА ФУНКЦИЯ?
    В CSV файле пустые ячейки превращаются в None (значение "пустота" в Python).
    У None нет метода .strip(), поэтому вызов None.strip() вызывает ошибку:
        AttributeError: 'NoneType' object has no attribute 'strip'
    
    Эта функция проверяет: если значение None — возвращаем пустую строку "".
    """
    # Получаем значение из словаря по ключу
    # Например: row.get('station_name') вернёт "Китай-город" или None
    value = row.get(key)
    
    # Если значение равно None (пустая ячейка в CSV)...
    if value is None:
        # ...возвращаем пустую строку
        return ""
    
    # Если значение есть:
    # 1. str(value) - превращаем его в строку (на всякий случай, если вдруг число)
    # 2. .strip() - удаляет пробелы в начале и конце строки
    # Например: "  Новокузнецкая  " → "Новокузнецкая"
    return str(value).strip()

# ============================================================
# ШАГ 5: ЗАГРУЖАЕМ ДАННЫЕ ИЗ CSV ФАЙЛА
# ============================================================

# Выводим сообщение о начале загрузки
print("\n📂 Загружаем данные из stations.csv...")

# Словарь для кэширования линий (чтобы не искать ID каждой линии в БД каждый раз)
# Структура: {'название_линии': ID_в_базе}
# Например: {'Кольцевая линия': 1, 'Сокольническая линия': 2}
lines_cache = {}

# Словарь для кэширования станций
# Структура: {'название_станции_ID_линии': ID_станции_в_базе}
# Например: {'Новокузнецкая_1': 5, 'Комсомольская_2': 7}
stations_cache = {}

# Счётчики для статистики
lines_count = 0     # сколько линий добавили в базу
stations_count = 0  # сколько станций добавили в базу
places_count = 0    # сколько мест добавили в базу
skipped_count = 0   # сколько строк CSV пропустили (из-за ошибок или пустых данных)

# Открываем CSV файл для чтения
# 'r' - режим чтения (read)
# encoding='utf-8' - кодировка для правильного чтения русских букв
with open('stations.csv', 'r', encoding='utf-8') as file:
    
    # csv.DictReader - читает CSV и превращает каждую строку в словарь
    # Первая строка файла (с заголовками) становится ключами словаря
    # Например: {'station_name': 'Новокузнецкая', 'line': 'Замоскворецкая', ...}
    reader = csv.DictReader(file)
    
    # Запускаем цикл по каждой строке CSV файла
    # Переменная row на каждом шаге содержит один словарь (одну строку)
    for row in reader:
        
        # ============================================================
        # ПОЛУЧАЕМ ДАННЫЕ ИЗ ТЕКУЩЕЙ СТРОКИ (БЕЗОПАСНО)
        # ============================================================
        
        # safe_get() безопасно получает значение, обрабатывая None
        # Каждая переменная теперь содержит строку (или пустую строку)
        line_name = safe_get(row, 'line')                 # Название линии метро
        station_name = safe_get(row, 'station_name')      # Название станции
        place_name = safe_get(row, 'place_name')          # Название места (кафе, музей...)
        fact = safe_get(row, 'fact')                      # Интересный факт о станции
        place_type = safe_get(row, 'place_type')          # Тип места (кафе, музей, парк...)
        description = safe_get(row, 'place_description')  # Описание места
        
        # --- ОБРАБАТЫВАЕМ ВРЕМЯ ПЕШКОМ (минуты) ---
        # safe_get() уже вернула строку (или пустую строку)
        walking_str = safe_get(row, 'walking_minutes')
        
        # Значение по умолчанию - 0 минут
        walking = 0
        
        # Если строка не пустая...
        if walking_str:
            # Пытаемся превратить строку в число
            try:
                walking = int(walking_str)  # Например: "5" → 5
            except:
                # Если не получилось (например там буквы "пять") - оставляем 0
                # pass означает "ничего не делай, просто продолжай"
                pass  # walking уже равен 0
        
        # ============================================================
        # ПРОВЕРКА НАЛИЧИЯ ОБЯЗАТЕЛЬНЫХ ПОЛЕЙ
        # ============================================================
        
        # Если нет названия линии, станции или места - пропускаем строку
        # Потому что без этих данных строка бесполезна для базы
        # not line_name - проверяет: пустая ли строка? Если да, то True
        if not line_name or not station_name or not place_name:
            skipped_count += 1  # Увеличиваем счётчик пропущенных на 1
            continue            # continue - переходим к следующей строке, эту не обрабатываем
        
        # ============================================================
        # ДОБАВЛЯЕМ ЛИНИЮ (если ещё не добавляли такую)
        # ============================================================
        
        # Проверяем, есть ли уже такая линия в нашем словаре-кэше
        # Если нет - значит, нужно добавить её в базу данных
        if line_name not in lines_cache:
            
            # SQL-запрос для добавления новой линии
            # INSERT INTO lines - добавить новую запись в таблицу lines
            # (name) - поле, которое мы заполняем
            # VALUES (%s) - значение (плейсхолдер %s подставится позже)
            # RETURNING id - вернуть ID созданной записи (чтобы мы знали, какой номер у линии)
            cursor.execute(
                "INSERT INTO lines (name) VALUES (%s) RETURNING id",
                (line_name,)  # Кортеж с одним значением (запятая важна, иначе не кортеж)
            )
            
            # fetchone() - получает результат запроса (одну строку)
            # fetchone() возвращает кортеж, например (5,)
            # [0] - берём первый элемент кортежа (ID новой линии)
            line_id = cursor.fetchone()[0]
            
            # Сохраняем в словарь-кэш: название_линии → её ID
            # В следующий раз, когда встретится эта же линия, мы сразу возьмём ID отсюда
            lines_cache[line_name] = line_id
            
            # Увеличиваем счётчик линий на 1
            lines_count += 1
            
            # Выводим сообщение о добавленной линии (чтобы видеть прогресс)
            print(f"   + Линия: {line_name}")
        
        # Получаем ID линии из кэша (откуда? мы сохранили его несколькими строками выше)
        line_id = lines_cache[line_name]
        
        # ============================================================
        # ДОБАВЛЯЕМ СТАНЦИЮ (если ещё не добавляли такую)
        # ============================================================
        
        # Формируем уникальный ключ для станции
        # Берём название станции и ID линии (на случай одинаковых названий на разных линиях)
        # Например: "Новокузнецкая_1" и "Новокузнецкая_2" - это разные станции
        station_key = f"{station_name}_{line_id}"
        
        # Проверяем, есть ли уже такая станция в кэше
        if station_key not in stations_cache:
            
            # Если факт пустой - подставляем None (в базе данных это NULL)
            # None означает "нет значения" или "пусто"
            # Условие: fact if fact else None
            # - если fact не пустая строка → берём fact
            # - если fact пустая строка → ставим None
            fact_value = fact if fact else None
            
            # SQL-запрос для добавления новой станции
            # %s - плейсхолдеры, значения будут подставлены позже из кортежа
            cursor.execute(
                "INSERT INTO stations (name, line_id, fact) VALUES (%s, %s, %s) RETURNING id",
                (station_name, line_id, fact_value)
            )
            
            # Получаем ID созданной станции
            station_id = cursor.fetchone()[0]
            
            # Сохраняем в кэш (ключ → ID станции)
            stations_cache[station_key] = station_id
            
            # Увеличиваем счётчик станций на 1
            stations_count += 1
        
        # Получаем ID станции из кэша
        station_id = stations_cache[station_key]
        
        # ============================================================
        # ДОБАВЛЯЕМ МЕСТО (ДОСТОПРИМЕЧАТЕЛЬНОСТЬ)
        # ============================================================
        
        # Если тип места пустой - ставим None (в базе NULL)
        # place_type if place_type else None
        place_type_value = place_type if place_type else None
        
        # Если описание пустое - ставим None
        description_value = description if description else None
        
        # SQL-запрос для добавления места
        # INSERT INTO places - добавляем новую запись в таблицу places
        # VALUES (%s, %s, %s, %s, %s) - 5 значений, которые подставятся вместо %s:
        #   1. station_id - ID станции (к какому метро относится это место)
        #   2. place_name - название места (например, "Третьяковская галерея")
        #   3. place_type_value - тип места (например, "музей") или NULL
        #   4. description_value - описание места (длинный текст) или NULL
        #   5. walking - сколько минут идти пешком от выхода из метро
        cursor.execute("""
            INSERT INTO places (station_id, name, place_type, description, walking_minutes)
            VALUES (%s, %s, %s, %s, %s)
        """, (station_id, place_name, place_type_value, description_value, walking))
        
        # Увеличиваем счётчик мест на 1
        places_count += 1
        
        # Каждые 100 мест выводим сообщение о прогрессе
        # % 100 - оператор "остаток от деления на 100"
        # Если остаток равен 0, значит число делится на 100 без остатка
        # Например: 100 % 100 = 0, 200 % 100 = 0, 150 % 100 = 50 (не выводим)
        if places_count % 100 == 0:
            print(f"   ... загружено {places_count} мест")

# ============================================================
# ШАГ 6: СОХРАНЯЕМ ИЗМЕНЕНИЯ В БАЗЕ ДАННЫХ
# ============================================================

# commit() - сохраняет все изменения
# Без commit() все вставки будут отменены при закрытии соединения
# Это механизм транзакций: либо все изменения сохранились, либо ничего
# Это важно для целостности данных
conn.commit()
print("\n💾 Изменения сохранены")

# ============================================================
# ШАГ 7: ВЫВОДИМ СТАТИСТИКУ ЗАГРУЗКИ
# ============================================================

# \n - символ новой строки (перенос строки)
print("\n" + "=" * 50)  # Печатаем 50 знаков "=" (разделитель)
print("📊 СТАТИСТИКА ЗАГРУЗКИ:")
print("=" * 50)

# f"текст {переменная}" - f-строка, подставляет значение переменной в текст
print(f"   • Линий: {lines_count}")
print(f"   • Станций: {stations_count}")
print(f"   • Мест: {places_count}")
print(f"   • Пропущено строк: {skipped_count}")
print("=" * 50)

# ============================================================
# ШАГ 8: ПРОВЕРКА - ВЫВОДИМ ПРИМЕР ДАННЫХ
# ============================================================

print("\n🔍 ПРИМЕР ЗАГРУЖЕННЫХ ДАННЫХ:")

# Сложный SQL-запрос с JOIN и GROUP BY
# Разберём запрос по частям:
#
# SELECT s.name, COUNT(p.id) as places_count
#   - выбираем название станции (s.name)
#   - и количество мест у этой станции (COUNT(p.id))
#   - "as places_count" даёт этому столбцу понятное имя
#
# FROM stations s
#   - основная таблица - stations (станции)
#   - буква s после названия таблицы - это псевдоним (сокращение)
#
# LEFT JOIN places p ON s.id = p.station_id
#   - присоединяем таблицу places (места), даём ей псевдоним p
#   - условие соединения: s.id = p.station_id (ID станции в таблице мест)
#   - LEFT JOIN означает: даже если у станции нет мест, она попадёт в результат
#
# GROUP BY s.id
#   - группируем результат по каждой станции отдельно
#   - Чтобы COUNT(p.id) считал места отдельно для каждой станции
#
# ORDER BY places_count DESC
#   - сортируем результат по убыванию (DESC = descending)
#   - Самая насыщенная станция (с наибольшим количеством мест) будет первой
#
# LIMIT 5
#   - показываем только первые 5 записей (топ-5 станций)
cursor.execute("""
    SELECT s.name, COUNT(p.id) as places_count
    FROM stations s
    LEFT JOIN places p ON s.id = p.station_id
    GROUP BY s.id
    ORDER BY places_count DESC
    LIMIT 5
""")

print("   Топ-5 станций по количеству мест:")

# fetchall() - получаем все строки результата запроса
# Каждая строка - это кортеж (название_станции, количество_мест)
for row in cursor.fetchall():
    # row[0] - первый элемент кортежа (название станции)
    # row[1] - второй элемент кортежа (количество мест)
    print(f"      🚇 {row[0]} — {row[1]} мест")

# ============================================================
# ШАГ 9: ЗАКРЫВАЕМ СОЕДИНЕНИЕ С БАЗОЙ ДАННЫХ
# ============================================================

# Закрываем курсор (освобождаем ресурсы)
# Курсор больше не нужен, данные уже загружены
cursor.close()

# Закрываем соединение с базой данных
# После этого подключение разрывается
conn.close()

# Выводим финальное сообщение об успешном завершении
print("\n✅ ГОТОВО! Все данные загружены в PostgreSQL")