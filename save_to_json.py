# save_to_json.py
# Эта программа читает CSV файл с достопримечательностями метро,
# группирует их по станциям и сохраняет результат в JSON файл.
# JSON - это универсальный формат, который понимают все языки программирования.

# ============================================================
# ИМПОРТ НЕОБХОДИМЫХ МОДУЛЕЙ
# ============================================================

import csv   # Модуль для работы с CSV файлами (чтение таблиц)
import json  # Модуль для работы с JSON форматом (сохранение данных)

# ============================================================
# ЧАСТЬ 1: ЧИТАЕМ CSV ФАЙЛ
# ============================================================

# Открываем файл stations.csv для чтения
# 'r' - режим чтения (read)
# encoding='utf-8' - кодировка для правильного отображения русских букв
with open('stations.csv', 'r', encoding='utf-8') as file:
    
    # csv.DictReader - специальный объект, который читает CSV
    # Первая строка файла становится ключами словаря
    # Каждая следующая строка становится значениями
    # Например: {'station_name': 'Китай-город', 'line': 'Калужско-Рижская', ...}
    reader = csv.DictReader(file)
    
    # Превращаем объект reader в обычный список словарей
    # Теперь rows - это список, где каждый элемент = одна строка из CSV
    rows = list(reader)

# ============================================================
# ЧАСТЬ 2: ГРУППИРУЕМ ДАННЫЕ ПО СТАНЦИЯМ
# ============================================================

# Создаём пустой словарь.
# Структура будет такой:
# {
#   "Название станции": {
#       "line": "название линии",
#       "fact": "интересный факт",
#       "places": [ {место1}, {место2}, ... ]
#   }
# }
stations_dict = {}

# Запускаем цикл по каждой строке из CSV файла
# Переменная row на каждом шаге содержит один словарь (одну строку)
for row in rows:
    
    # ---------- ПОЛУЧАЕМ НАЗВАНИЕ СТАНЦИИ ----------
    # .get('station_name') - безопасно получаем значение по ключу
    # Если ключа нет, вернёт None (а не вызовет ошибку)
    station_name = row.get('station_name')
    
    # Проверяем: если значение равно None (пустая ячейка) - пропускаем строку
    if station_name is None:
        continue  # continue - переходим к следующей строке, эту не обрабатываем
    
    # Превращаем значение в строку (на всякий случай)
    # strip() - удаляет пробелы в начале и конце строки
    station_name = str(station_name).strip()
    
    # Если после удаления пробелов строка пустая - тоже пропускаем
    if not station_name:
        continue
    
    # ---------- ПРОВЕРЯЕМ: ЕСТЬ ЛИ УЖЕ ТАКАЯ СТАНЦИЯ В СЛОВАРЕ ----------
    # Если станции с таким именем ещё нет в словаре...
    if station_name not in stations_dict:
        
        # ---------- ОБРАБАТЫВАЕМ ПОЛЕ "line" (линия метро) ----------
        # Получаем значение линии из CSV
        line = row.get('line')
        
        # Если значение отсутствует (None) - ставим текст по умолчанию
        if line is None:
            line = 'Не указана'
        else:
            # Превращаем в строку и удаляем пробелы
            line = str(line).strip()
            # Если после удаления пробелов пусто - ставим текст по умолчанию
            if not line:
                line = 'Не указана'
        
        # ---------- ОБРАБАТЫВАЕМ ПОЛЕ "fact" (интересный факт) ----------
        # Получаем значение факта из CSV
        fact = row.get('fact')
        
        # Если значение отсутствует - ставим текст по умолчанию
        if fact is None:
            fact = 'Интересный факт пока не добавлен'
        else:
            # Превращаем в строку и удаляем пробелы
            fact = str(fact).strip()
            # Если после удаления пробелов пусто - ставим текст по умолчанию
            if not fact:
                fact = 'Интересный факт пока не добавлен'
        
        # ---------- СОЗДАЁМ НОВУЮ СТАНЦИЮ В СЛОВАРЕ ----------
        # Ключ - название станции (station_name)
        # Значение - новый словарь с тремя полями:
        #   'line' - название линии
        #   'fact' - интересный факт
        #   'places' - пустой список (сюда будем добавлять места)
        stations_dict[station_name] = {
            'line': line,
            'fact': fact,
            'places': []  # [] - это пустой список
        }
    
    # ---------- ОБРАБАТЫВАЕМ ПОЛЕ "place_name" (название места) ----------
    # Эта часть выполняется для каждой строки, даже если станция уже существует
    # Получаем название места (достопримечательности, кафе, парка и т.д.)
    place_name = row.get('place_name')
    
    # Если названия места нет - пропускаем эту строку
    # Место без имени добавлять бессмысленно
    if place_name is None:
        continue
    
    # Превращаем в строку и удаляем пробелы
    place_name = str(place_name).strip()
    
    # Если после удаления пробелов пусто - тоже пропускаем
    if not place_name:
        continue
    
    # ---------- ОБРАБАТЫВАЕМ ПОЛЕ "walking_minutes" (минуты пешком) ----------
    # Это самое сложное поле, потому что оно может быть:
    # - None (пустая ячейка)
    # - пустой строкой (тоже пусто)
    # - строкой с числом "5"
    # - строкой с текстом "около пяти" (редко, но бывает)
    walking_minutes = row.get('walking_minutes')
    
    # Значение по умолчанию - 0 минут (если ничего не указано)
    walking = 0
    
    # Проверяем: если значение НЕ равно None (то есть что-то записано)
    if walking_minutes is not None:
        # Пытаемся превратить значение в целое число
        try:
            # int() превращает строку "5" в число 5
            walking = int(walking_minutes)
        except (ValueError, TypeError):
            # ValueError - возникает, если строку нельзя превратить в число
            #   Например, walking_minutes = "пять" или ""
            # TypeError - возникает, если значение вообще не строка
            # В обоих случаях оставляем walking = 0
            walking = 0
    
    # ---------- ОБРАБАТЫВАЕМ ПОЛЕ "place_type" (тип места) ----------
    # Тип места: кафе, музей, парк, магазин, театр и т.д.
    place_type = row.get('place_type')
    
    # Если тип не указан - ставим "другое"
    if place_type is None:
        place_type = 'другое'
    else:
        # Превращаем в строку и удаляем пробелы
        place_type = str(place_type).strip()
        # Если после удаления пробелов пусто - тоже ставим "другое"
        if not place_type:
            place_type = 'другое'
    
    # ---------- ОБРАБАТЫВАЕМ ПОЛЕ "place_description" (описание места) ----------
    # Короткое описание того, что это за место
    place_description = row.get('place_description')
    
    # Если описания нет - ставим текст по умолчанию
    if place_description is None:
        place_description = 'Описание отсутствует'
    else:
        # Превращаем в строку и удаляем пробелы
        place_description = str(place_description).strip()
        # Если после удаления пробелов пусто - ставим текст по умолчанию
        if not place_description:
            place_description = 'Описание отсутствует'
    
    # ---------- СОЗДАЁМ СЛОВАРЬ ДЛЯ ОДНОГО МЕСТА ----------
    # Упаковываем все данные о месте в один словарь
    place = {
        'name': place_name,                 # название места (строка)
        'type': place_type,                 # тип места (строка)
        'description': place_description,   # описание места (строка)
        'walking_minutes': walking          # время пешком (число)
    }
    
    # ---------- ДОБАВЛЯЕМ МЕСТО К СТАНЦИИ ----------
    # Находим в словаре станцию по названию
    # Обращаемся к её полю 'places' (это список)
    # .append(place) - добавляем новое место в конец списка
    stations_dict[station_name]['places'].append(place)

# ============================================================
# ЧАСТЬ 3: СОХРАНЯЕМ РЕЗУЛЬТАТ В JSON ФАЙЛ
# ============================================================

# Открываем файл stations.json для записи
# 'w' - режим записи (write) - если файл существует, он будет перезаписан
# encoding='utf-8' - кодировка для сохранения русских букв
with open('stations.json', 'w', encoding='utf-8') as json_file:
    
    # json.dump() - функция, которая сохраняет Python-объект в JSON файл
    # Параметры:
    #   1. stations_dict - что сохраняем (наш словарь)
    #   2. json_file - куда сохраняем (открытый файл)
    #   3. ensure_ascii=False - НЕ превращать русские буквы в \u0438\u043a...
    #      Если поставить True, то "Москва" превратится в "\u041c\u043e\u0441\u043a\u0432\u0430"
    #   4. indent=2 - делать отступы в 2 пробела для удобного чтения
    #      Без этого всё будет в одну строку
    json.dump(stations_dict, json_file, ensure_ascii=False, indent=2)

# ============================================================
# ЧАСТЬ 4: ВЫВОДИМ ОТЧЁТ О ВЫПОЛНЕНИИ
# ============================================================

# Выводим сообщение об успешном сохранении
# \n - символ новой строки (перенос строки)
print("✅ Готово! Данные сохранены в файл 'stations.json'")

# len(stations_dict) - количество станций в словаре
# f"текст {переменная}" - f-строка, подставляет значение переменной
print(f"   Всего станций: {len(stations_dict)}")

# Подсчитываем общее количество мест
# sum() - складывает числа
# len(info['places']) - количество мест на каждой станции
# stations_dict.values() - берём все значения из словаря (данные станций)
total_places = sum(len(info['places']) for info in stations_dict.values())
print(f"   Всего мест: {total_places}")

# ============================================================
# ЧАСТЬ 5: ПОКАЗЫВАЕМ ПРИМЕР JSON ДАННЫХ
# ============================================================

# Выводим заголовок для образца
print("\n📄 Первая станция в JSON (образец):")

# Получаем список всех ключей (названий станций) из словаря
# stations_dict.keys() - это специальный объект-представление ключей
# list(...) - превращаем его в обычный список
# [0] - берём первый элемент списка (самую первую станцию)
first_station_name = list(stations_dict.keys())[0]

# Выводим название первой станции
print(f"   {first_station_name}:")

# Получаем данные первой станции по её названию
first_station_data = stations_dict[first_station_name]

# Выводим название линии
print(f"      линия: {first_station_data['line']}")

# len(first_station_data['places']) - количество мест у этой станции
print(f"      мест: {len(first_station_data['places'])}")

# Если у первой станции есть хотя бы одно место...
if first_station_data['places']:
    # Берём первое место (индекс [0]) из списка мест
    first_place = first_station_data['places'][0]
    # Выводим название первого места
    print(f"      первое место: {first_place['name']}")