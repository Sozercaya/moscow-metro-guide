# run.py
# ============================================================
# ТОЧКА ВХОДА В ПРИЛОЖЕНИЕ
# ============================================================
# 
# Этот файл — самая первая дверь в ваше приложение.
# Когда вы вводите в терминале: python3 run.py
# Python начинает выполнение именно с этого файла.
#
# Задача run.py:
# 1. Импортировать функцию create_app из папки app
# 2. Создать экземпляр приложения
# 3. Запустить веб-сервер, который будет слушать запросы пользователей
#
# Весь остальной код (маршруты, работа с БД, HTML, CSS, JS)
# лежит в других файлах — сюда мы их только подключаем.
# ============================================================

# ============================================================
# ИМПОРТ ФУНКЦИИ create_app ИЗ ПАПКИ app
# ============================================================

# from app import create_app
#   from app - обращаемся к папке app (там лежит файл __init__.py)
#   import create_app - импортируем функцию с именем create_app
#   из файла app/__init__.py
#
# Почему именно так?
#   В папке app есть специальный файл __init__.py.
#   Он выполняется при импорте папки как модуля.
#   В нём определена функция create_app(), которая:
#     - создаёт Flask-приложение
#     - подключает настройки (config)
#     - регистрирует маршруты (routes)
#
# Благодаря этому импорту мы можем "принести" в этот файл
# готовое приложение, которое уже полностью настроено.
from app import create_app

# ============================================================
# СОЗДАНИЕ ПРИЛОЖЕНИЯ
# ============================================================

# Вызываем функцию create_app(), которая возвращает готовое
# Flask-приложение. Это приложение (объект класса Flask) умеет:
#   - обрабатывать HTTP-запросы (GET, POST, ...)
#   - определять маршруты (куда идти по адресу / или /api/...)
#   - отдавать HTML-страницы, JSON-данные, картинки и т.д.
#
# Мы сохраняем это приложение в переменную app.
# Теперь app — это наш главный объект, который управляет всем сайтом.
app = create_app()

# ============================================================
# ЗАПУСК СЕРВЕРА
# ============================================================

# if __name__ == '__main__':
#   Это стандартная конструкция в Python.
#   Она проверяет: запущен ли этот файл напрямую (python3 run.py),
#   или его импортировали как модуль (from run import ...)
#
#   __name__ — специальная переменная Python.
#     - Если файл запущен напрямую, __name__ == '__main__'
#     - Если файл импортирован, __name__ равно имени файла ('run')
#
#   Зачем это нужно?
#     Чтобы код внутри if выполнялся ТОЛЬКО при прямом запуске.
#     Если бы кто-то импортировал run.py как модуль, сервер бы не запустился.
if __name__ == '__main__':
    
    # app.run() — метод Flask, который запускает встроенный веб-сервер.
    # Параметры:
    #   debug=True   - режим отладки
    #                  Что даёт:
    #                  - При изменении кода сервер перезагружается сам (не нужно перезапускать)
    #                  - При ошибке показывается подробная отладочная страница в браузере
    #                  - В терминале выводятся подробные логи
    #                  ⚠️ Внимание: на реальном (боевом) сервере debug=True НЕЛЬЗЯ включать —
    #                  это опасно для безопасности. Но для разработки на домашнем компьютере — идеально.
    #
    #   host='0.0.0.0' - слушаем запросы со всех сетевых интерфейсов
    #                    Что это значит:
    #                    - '127.0.0.1' — только с этого же компьютера (localhost)
    #                    - '0.0.0.0'   — с любого устройства в локальной сети
    #                    То есть если вы откроете сайт с телефона, подключённого к той же Wi-Fi,
    #                    вы сможете зайти на сайт по IP-адресу компьютера.
    #
    #   port=5000    - порт, на котором работает сервер
    #                  По умолчанию Flask использует порт 5000.
    #                  В браузере нужно открывать: http://127.0.0.1:5000
    #                  Если порт занят, Flask выдаст ошибку (можно сменить на 5001, 8080 и т.д.)
    app.run(debug=True, host='0.0.0.0', port=5000)

# ============================================================
# ЧТО ПРОИСХОДИТ ПОСЛЕ ЗАПУСКА
# ============================================================
#
# 1. Python начинает выполнять код сверху вниз
# 2. Импортирует create_app из app/__init__.py
# 3. Вызывает create_app(), которая создаёт и настраивает Flask-приложение
# 4. Сохраняет приложение в переменную app
# 5. Проверяет, что файл запущен напрямую (__name__ == '__main__')
# 6. Запускает сервер через app.run()
# 7. Сервер начинает слушать порт 5000
# 8. В терминале появляется надпись:
#      * Running on http://127.0.0.1:5000
# 9. Теперь сервер ждёт запросов от браузера
# 10. Когда вы открываете сайт в браузере, сервер отвечает
# 11. В терминале появляются логи: кто зашёл, какую страницу запросил
# 12. Чтобы остановить сервер — нажать Ctrl+C
#
# ============================================================
# КАК ВЫГЛЯДИТ ЦЕПОЧКА ЗАПУСКА
# ============================================================
#
# run.py (вы запускаете здесь)
#    ↓
# app/__init__.py (create_app)
#    ↓
# app/config.py (настройки)
#    ↓
# app/routes.py (маршруты)
#    ↓
# Сервер запущен! (ждёт запросы)
#    ↓
# Браузер: http://127.0.0.1:5000
#    ↓
# Flask получает запрос → ищет маршрут '/' в routes.py
#    ↓
# routes.py вызывает models.py → PostgreSQL
#    ↓
# Данные возвращаются → отображаются через index.html
#    ↓
# Пользователь видит сайт!
#
# ============================================================
# ПОЧЕМУ ТАКАЯ СТРУКТУРА?
# ============================================================
#
# 1. Разделение ответственности:
#    - run.py отвечает только за запуск
#    - __init__.py отвечает за сборку приложения
#    - config.py отвечает за настройки
#    - routes.py отвечает за URL-адреса
#    - models.py отвечает за базу данных
#    - templates/ отвечают за внешний вид
#    - static/ отвечает за стили и скрипты
#
# 2. Профессиональная практика (фабрика приложений):
#    Такая структура называется Application Factory.
#    Она позволяет:
#      - Создавать несколько экземпляров приложения (например, для тестов)
#      - Легко переиспользовать код в других проектах
#      - Удобно расширять приложение
#      - Понятно новым разработчикам
#
# 3. Это стандарт для Flask-приложений:
#    Такую структуру рекомендуют в официальной документации Flask.
#    Работодатели увидят, что вы знаете правильные подходы.
# ============================================================