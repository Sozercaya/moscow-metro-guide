# run.py
# Точка входа в приложение
import os
from dotenv import load_dotenv
from app import create_app

# Загружаем переменные из .env файла (если есть)
load_dotenv()

app = create_app()

if __name__ == '__main__':

    # 1. DEBUG
    debug_mode = os.environ.get('FLASK_DEBUG', 'false').lower() == 'true'
    
    # 2. HOST
    host = os.environ.get('FLASK_HOST', '0.0.0.0')

    # 3. PORT (с защитой от нечисловых значений)
    raw_port = os.environ.get('FLASK_PORT', '5000')
    try:
        port = int(raw_port)
    except ValueError:
        port = 5000
        print(f"⚠️ Ошибка: FLASK_PORT='{raw_port}' не является числом. Использую порт 5000")

    # Выводим настройки перед запуском
    print(f"🚀 Запуск сервера:")
    print(f"   • Режим отладки (debug): {'включён' if debug_mode else 'выключен'}")
    print(f"   • Хост: {host}")
    print(f"   • Порт: {port}")
    print(f"   • Сайт доступен по адресу: http://{host}:{port}")

    app.run(
        debug=debug_mode,
        host=host,
        port=port
    )

# ============================================================
# ЧТО ПРОИСХОДИТ ПОСЛЕ ЗАПУСКА
# ============================================================
#
# 1. Python начинает выполнять код сверху вниз
# 2. Импортирует create_app из app/__init__.py
# 3. Вызывает create_app(), которая создаёт и настраивает Flask-приложение
# 4. Сохраняет приложение в переменную app
# 5. Проверяет, что файл запущен напрямую (__name__ == '__main__')
# 6. Запускает сервер через app.run()
# 7. Сервер начинает слушать порт 5000
# 8. В терминале появляется надпись:
#      * Running on http://127.0.0.1:5000
# 9. Теперь сервер ждёт запросов от браузера
# 10. Когда вы открываете сайт в браузере, сервер отвечает
# 11. В терминале появляются логи: кто зашёл, какую страницу запросил
# 12. Чтобы остановить сервер — нажать Ctrl+C
#
# ============================================================
# КАК ВЫГЛЯДИТ ЦЕПОЧКА ЗАПУСКА
# ============================================================
#
# run.py (вы запускаете здесь)
#    ↓
# app/__init__.py (create_app)
#    ↓
# app/config.py (настройки)
#    ↓
# app/routes.py (маршруты)
#    ↓
# Сервер запущен! (ждёт запросы)
#    ↓
# Браузер: http://127.0.0.1:5000
#    ↓
# Flask получает запрос → ищет маршрут '/' в routes.py
#    ↓
# routes.py вызывает models.py → PostgreSQL
#    ↓
# Данные возвращаются → отображаются через index.html
#    ↓
# Пользователь видит сайт!
#
# ============================================================
# ПОЧЕМУ ТАКАЯ СТРУКТУРА?
# ============================================================
#
# 1. Разделение ответственности:
#    - run.py отвечает только за запуск
#    - __init__.py отвечает за сборку приложения
#    - config.py отвечает за настройки
#    - routes.py отвечает за URL-адреса
#    - models.py отвечает за базу данных
#    - templates/ отвечают за внешний вид
#    - static/ отвечает за стили и скрипты
#
# 2. Профессиональная практика (фабрика приложений):
#    Такая структура называется Application Factory.
#    Она позволяет:
#      - Создавать несколько экземпляров приложения (например, для тестов)
#      - Легко переиспользовать код в других проектах
#      - Удобно расширять приложение
#      - Понятно новым разработчикам
#
# 3. Это стандарт для Flask-приложений:
#    Такую структуру рекомендуют в официальной документации Flask.
#    Работодатели увидят, что вы знаете правильные подходы.
# ============================================================