# load_data.py
# Это программа, которая читает файл с достопримечательностями у станций метро
# и группирует их по станциям для красивого вывода

import csv # Импортируем модуль csv - он умеет читать и писать CSV файлы

# ============================================================
# ЧАСТЬ 1: ЧИТАЕМ CSV ФАЙЛ
# ============================================================

# Открываем файл stations.csv для чтения
# 'with' автоматически закроет файл после того, как мы закончим
# 'r' означает read (читать) - можно не писать, это значение по умолчанию
# encoding='utf-8' - указываем кодировку, чтобы правильно читались русские буквы

with open('stations.csv', encoding='utf-8') as file:
    
    # csv.DictReader - специальный объект, который читает CSV и превращает каждую строку в словарь
    # Первая строка файла (с заголовками) становится ключами словаря
    # Например: {'station_name': 'Китай-город', 'line': 'Калужско-Рижская', ...}
    reader = csv.DictReader(file)

    # list(reader) - превращаем объект reader в обычный список словарей
    # Теперь в переменной rows лежит список, где каждый элемент - словарь с данными одной строки
    rows = list(reader)

# ============================================================
# ЧАСТЬ 2: ГРУППИРУЕМ ДАННЫЕ ПО СТАНЦИЯМ
# ============================================================

# Создаём пустой словарь, в котором будем хранить данные о станциях
# Ключ = название станции, Значение = словарь с полями: line, fact, places
stations_dict = {}

# Запускаем цикл по всем строкам (записям) из CSV файла
# Переменная row на каждом шаге содержит один словарь (одну строку из файла)
for row in rows:

    # Получаем название станции из поля 'station_name'
    # .get('station_name') - безопасный способ получить значение по ключу
    # Если ключа нет, вернёт None вместо ошибки
    station_name = row.get('station_name')
    
    # ========== ПРОВЕРКА: есть ли у строки название станции ==========
    # Если station_name равно None (пустое значение в файле) - пропускаем эту строку
    if station_name is None:
        continue # continue означает "перейти к следующей итерации цикла", эту строку пропускаем
    
    # Превращаем название станции в строку (на всякий случай) и убираем лишние пробелы по краям
    station_name = str(station_name).strip()

    # Если после удаления пробелов строка пустая - тоже пропускаем
    if not station_name:
        continue
    
     # ========== ПРОВЕРКА: есть ли уже такая станция в словаре ==========
    # Если станции с таким названием ещё нет в нашем словаре...
    if station_name not in stations_dict:
        
        # ---------- ОБРАБОТКА ПОЛЯ "line" (линия метро) ----------
        # Получаем значение линии из CSV
        line = row.get('line')
         # Если значения нет (None) - ставим текст "Не указана"
        if line is None:
            line = 'Не указана'
        else:

            # Превращаем в строку и убираем пробелы
            line = str(line).strip()

            # Если после удаления пробелов получилась пустая строка - тоже ставим "Не указана"
            if not line:
                line = 'Не указана'
        
        # ---------- ОБРАБОТКА ПОЛЯ "fact" (интересный факт) ----------
        # Получаем значение факта из CSV
        fact = row.get('fact')
        # Если значения нет - ставим текст по умолчанию
        if fact is None:
            fact = 'Интересный факт пока не добавлен'
        else:

            # Превращаем в строку и убираем пробелы
            fact = str(fact).strip()

            # Если после удаления пробелов пусто - ставим текст по умолчанию
            if not fact:
                fact = 'Интересный факт пока не добавлен'
        
        # ---------- ДОБАВЛЯЕМ НОВУЮ СТАНЦИЮ В СЛОВАРЬ ----------
        # Для этой станции создаём словарь с тремя ключами:
        # 'line' - название линии
        # 'fact' - интересный факт
        # 'places' - пустой список, куда будем добавлять места
        stations_dict[station_name] = {
            'line': line,
            'fact': fact,
            'places': [] # [] означает пустой список
        }
    
    # ========== ДОБАВЛЯЕМ МЕСТО К СТАНЦИИ ==========
    # Эта часть выполняется КАЖДЫЙ раз, даже если станция уже была добавлена ранее
    
    # ---------- ОБРАБОТКА ПОЛЯ "place_name" (название места) ----------
    # Получаем название места из CSV
    place_name = row.get('place_name')

    # Если названия места нет - пропускаем эту строку (не можем добавить место без названия)
    if place_name is None:
        continue
    
    # Превращаем в строку и убираем пробелы
    place_name = str(place_name).strip()
    
    # Если после удаления пробелов пусто - тоже пропускаем
    if not place_name:
        continue
    
     # ---------- ОБРАБОТКА ПОЛЯ "walking_minutes" (минуты пешком) ----------
    # Получаем значение минут из CSV
    # Это самое сложное поле, потому что оно может быть:
    # - None (пустая ячейка)
    # - пустой строкой (тоже пусто, по-другому)
    # - строкой с числом "5"
    # - строкой с текстом "около пяти"
    walking_minutes = row.get('walking_minutes')
    # Задаём значение по умолчанию - 0 минут
    walking = 0  # значение по умолчанию
    
    # Проверяем: если значение НЕ равно None (то есть что-то записано)
    if walking_minutes is not None:
        # Если это не None, пробуем превратить в число
        try:
            # int() превращает строку "5" в число 5
            walking = int(walking_minutes)
        except (ValueError, TypeError):
            # Если не получилось (например, там текст "пять" или пустая строка)
            # Оставляем walking = 0 (значение по умолчанию)
            # ValueError возникает, если строка не похожа на число
            # TypeError возникает, если значение вообще не строка
            walking = 0
    
    # ---------- ОБРАБОТКА ПОЛЯ "place_type" (тип места) ----------
    # Получаем тип места (кафе, музей, парк...)
    place_type = row.get('place_type')

    # Если тип не указан - ставим "другое"
    if place_type is None:
        place_type = 'другое'
    else:

        # Превращаем в строку и убираем пробелы
        place_type = str(place_type).strip()

        # Если получилась пустая строка - тоже ставим "другое"
        if not place_type:
            place_type = 'другое'
    
    # ---------- ОБРАБОТКА ПОЛЯ "place_description" (описание места) ----------
    # Получаем описание места
    place_description = row.get('place_description')

    # Если описания нет - ставим текст по умолчанию
    if place_description is None:
        place_description = 'Описание отсутствует'
    else:

        # Превращаем в строку и убираем пробелы
        place_description = str(place_description).strip()
        if not place_description:
            # Если пусто - ставим текст по умолчанию
            place_description = 'Описание отсутствует'
    
    # ---------- СОЗДАЁМ СЛОВАРЬ ДЛЯ МЕСТА ----------
    # Теперь у нас есть все данные о месте, собираем их в один словарь
    place = {
        'name': place_name, # название места
        'type': place_type, # тип места (кафе, музей...)
        'description': place_description, # описание места
        'walking_minutes': walking # сколько минут идти от метро
    }

    # ---------- ДОБАВЛЯЕМ ЭТО МЕСТО К СТАНЦИИ ----------
    # Находим в словаре stations_dict запись для этой станции
    # и обращаемся к её списку places
    # .append(place) добавляет новое место в конец списка
    stations_dict[station_name]['places'].append(place)

# ============================================================
# ЧАСТЬ 3: ВЫВОДИМ РЕЗУЛЬТАТ НА ЭКРАН
# ============================================================

# Выводим общее количество станций (len() - длина словаря)
print(f"📊 Найдено {len(stations_dict)} станций\n")

# Выводим разделительную линию из 60 знаков равно
print("=" * 60)

# Запускаем цикл по всем станциям в словаре
# .items() возвращает пары (ключ, значение) для каждого элемента словаря
# station_name - название станции (ключ)
# info - словарь с данными станции (значение)
for station_name, info in stations_dict.items():

    # Выводим название станции с эмодзи
    print(f"\n🚇 СТАНЦИЯ: {station_name}")
    # Выводим название линии
    print(f"   🟢 Линия: {info['line']}")
    # Выводим интересный факт
    print(f"   📖 Факт: {info['fact']}")
     # Выводим заголовок со списком мест и количеством мест
    # len(info['places']) - количество элементов в списке мест
    print(f"\n   📍 Места рядом ({len(info['places'])} шт.):")
    # Если список мест пустой - выводим сообщение об этом
    if not info['places']:
        print("      (пока нет добавленных мест)")
    
    # Запускаем внутренний цикл по всем местам текущей станции
    for place in info['places']:
        # Получаем количество минут пешком до места
        minutes = place['walking_minutes']
        # Если время указано (больше 0) ...
        if minutes > 0:
            # Создаём визуализацию: одна точка за каждые 2 минуты
            # Например, 10 минут → 5 точек
            # min() ограничивает максимум 10 точек, чтобы не было слишком длинно
            dots = "●" * min(minutes // 2, 10)
            time_str = f"{minutes} мин пешком {dots}"
        else:
            # Если время не указано (0) - пишем "время не указано"
            time_str = "время не указано"
        
        # Выводим название места с отступом и маркером •
        print(f"      • {place['name']}")
        # Выводим тип места
        print(f"        Тип: {place['type']}")
        # Выводим расстояние
        print(f"        Расстояние: {time_str}")
        # Выводим описание, обрезая до 60 символов, чтобы не было слишком длинно
        # [ :60] - срез: берём символы с 0 по 60
        print(f"        Описание: {place['description'][:60]}")
        # Пустая строка для разделения мест
        print()

# ============================================================
# ЧАСТЬ 4: ВЫВОДИМ СТАТИСТИКУ
# ============================================================

# Выводим разделитель
print("=" * 60)

# Заголовок статистики
print("\n📈 Маленькая статистика:")

# Выводим количество станций
print(f"   Всего станций: {len(stations_dict)}")

# Считаем общее количество мест
# sum() - складывает числа
# len(info['places']) - количество мест на каждой станции
# for info in stations_dict.values() - проходим по всем станциям
total_places = sum(len(info['places']) for info in stations_dict.values())
print(f"   Всего мест: {total_places}")

# Находим станцию с наибольшим количеством мест
# max() - находит максимум
# stations_dict.items() - пары (название, данные)
# key=lambda x: len(x[1]['places']) - по чему сравниваем (по количеству мест)
# lambda - маленькая функция, которая из пары (название, данные) достаёт количество мест
if stations_dict: # Проверяем, что словарь не пустой (есть хотя бы одна станция)
    # best_station[0] - название станции
    # len(best_station[1]['places']) - количество мест у неё
    best_station = max(stations_dict.items(), key=lambda x: len(x[1]['places']))
    print(f"   🏆 Самая насыщенная станция: {best_station[0]} ({len(best_station[1]['places'])} мест)")